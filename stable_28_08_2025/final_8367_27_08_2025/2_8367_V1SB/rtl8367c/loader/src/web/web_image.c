int8 get_image(struct http_request_s *pReq, int32 image_idx)
{
    uint8 buf[32];

    if ((image_idx <= WEB_IMAGE_NONE) || (image_idx >= WEB_IMAGE_MAX))
        return FAILED;

    WEB_BEGIN(pReq);

    WEB_STATUS(pReq, HTTP_STATUS_OK);

    switch (image_idx)
    {
    case WEB_IMAGE_DOCUMENT_GIF:
        WEB_HEADER(pReq, "Content-Type: image/gif");
        sprintf(buf, "Content-Length: %u", (uint16)sizeof(gif_document));
        WEB_HEADER(pReq, buf);
        WEB_DATA(pReq, gif_document, sizeof(gif_document));
        break;
    case WEB_IMAGE_FOLDER_OPENED_GIF:
        WEB_HEADER(pReq, "Content-Type: image/gif");
        sprintf(buf, "Content-Length: %u", (uint16)sizeof(gif_folder_opened));
        WEB_HEADER(pReq, buf);
        WEB_DATA(pReq, gif_folder_opened, sizeof(gif_folder_opened));
        break;
    case WEB_IMAGE_FOLDER_CLOSED_GIF:
        WEB_HEADER(pReq, "Content-Type: image/gif");
        sprintf(buf, "Content-Length: %u", (uint16)sizeof(gif_folder_closed));
        WEB_HEADER(pReq, buf);
        WEB_DATA(pReq, gif_folder_closed, sizeof(gif_folder_closed));
        break;
        case WEB_IMAGE_PLUS_GIF:
            WEB_HEADER(pReq, "Content-Type: image/gif");
            sprintf(buf, "Content-Length: %u", (uint16)sizeof(gif_plus));
            WEB_HEADER(pReq, buf);
            WEB_DATA(pReq, gif_plus, sizeof(gif_plus));
            break;
        case WEB_IMAGE_MINUS_GIF:
        case WEB_IMAGE_TRANSPARENT_GIF:
            WEB_HEADER(pReq, "Content-Type: image/gif");
            sprintf(buf, "Content-Length: %u", (uint16)sizeof(gif_minus));
            WEB_HEADER(pReq, buf);
            WEB_DATA(pReq, gif_minus, sizeof(gif_minus));
            break;
    default:
        printf("%s():%d Error: Web image (%d) is not exist!\n", __FILE__, __LINE__);
        break;
    }

    WEB_END(pReq);

    return SUCCESS;
}

